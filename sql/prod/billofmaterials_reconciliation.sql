-- Reconciliation for PROD_STAGING.SAP.BILLOFMATERIALS. See docs/bom-slicing.md.
-- No row of the first result may show FAIL. A REVIEW row needs an explanation on the ticket.
-- Run as ENGINEER_ROLE after all 11 slices have loaded and the dynamic table has refreshed.
-- Check 5 reads DEV_RAW, so it needs DEV access. The QVD check is done by hand, because the QVD is not in Snowflake.

WITH slices AS (
  SELECT 1 AS slice, PLANT, BILLOFMATERIAL FROM PROD_RAW.SAP.BILLOFMATERIALS_01 UNION ALL
  SELECT 2, PLANT, BILLOFMATERIAL FROM PROD_RAW.SAP.BILLOFMATERIALS_02 UNION ALL
  SELECT 3, PLANT, BILLOFMATERIAL FROM PROD_RAW.SAP.BILLOFMATERIALS_03 UNION ALL
  SELECT 4, PLANT, BILLOFMATERIAL FROM PROD_RAW.SAP.BILLOFMATERIALS_04 UNION ALL
  SELECT 5, PLANT, BILLOFMATERIAL FROM PROD_RAW.SAP.BILLOFMATERIALS_05 UNION ALL
  SELECT 6, PLANT, BILLOFMATERIAL FROM PROD_RAW.SAP.BILLOFMATERIALS_06 UNION ALL
  SELECT 7, PLANT, BILLOFMATERIAL FROM PROD_RAW.SAP.BILLOFMATERIALS_07 UNION ALL
  SELECT 8, PLANT, BILLOFMATERIAL FROM PROD_RAW.SAP.BILLOFMATERIALS_08 UNION ALL
  SELECT 9, PLANT, BILLOFMATERIAL FROM PROD_RAW.SAP.BILLOFMATERIALS_09 UNION ALL
  SELECT 10, PLANT, BILLOFMATERIAL FROM PROD_RAW.SAP.BILLOFMATERIALS_10 UNION ALL
  SELECT 11, PLANT, BILLOFMATERIAL FROM PROD_RAW.SAP.BILLOFMATERIALS_11
),
per_slice AS (SELECT slice, COUNT(*) AS n FROM slices GROUP BY slice),
overlap AS (
  SELECT COUNT(*) AS n FROM (
    SELECT PLANT, BILLOFMATERIAL FROM slices GROUP BY PLANT, BILLOFMATERIAL HAVING COUNT(DISTINCT slice) > 1
  )
),
dev_plants AS (SELECT PLANT, COUNT(*) AS n FROM DEV_RAW.SAP.BILLOFMATERIALS GROUP BY PLANT),
prod_plants AS (SELECT PLANT, COUNT(*) AS n FROM PROD_STAGING.SAP.BILLOFMATERIALS GROUP BY PLANT),
plant_diff AS (
  SELECT COUNT(*) AS n FROM prod_plants p FULL OUTER JOIN dev_plants d ON p.PLANT = d.PLANT
  WHERE COALESCE(p.n, 0) <> COALESCE(d.n, 0)
)
,
checks AS (
  SELECT 1 AS ord, 'Combined rows equal sum of slices' AS check_name, (SELECT COUNT(*) FROM PROD_STAGING.SAP.BILLOFMATERIALS) AS actual, (SELECT SUM(n) FROM per_slice) AS expected, '=' AS op
  UNION ALL SELECT 2, 'Largest slice is 500000 rows or fewer', (SELECT MAX(n) FROM per_slice), 500000, '<='
  UNION ALL SELECT 3, 'Keys that appear in more than one slice', (SELECT n FROM overlap), 0, '='
  UNION ALL SELECT 4, 'Columns in the combined object', (SELECT COUNT(*) FROM PROD_STAGING.INFORMATION_SCHEMA.COLUMNS WHERE TABLE_SCHEMA = 'SAP' AND TABLE_NAME = 'BILLOFMATERIALS'), 29, '='
  UNION ALL SELECT 5, 'Plants whose count differs from DEV (explain each)', (SELECT n FROM plant_diff), 0, 'review'
)
SELECT check_name, actual, expected,
       CASE WHEN op = 'review' THEN IFF(actual = expected, 'PASS', 'REVIEW')
            WHEN (op = '=' AND actual = expected) OR (op = '<=' AND actual <= expected) THEN 'PASS'
            ELSE 'FAIL' END AS result
FROM checks
ORDER BY ord;

-- Detail: plants whose count differs from DEV. Explain each row on the ticket.
SELECT COALESCE(p.PLANT, d.PLANT) AS plant, p.n AS prod_rows, d.n AS dev_rows, COALESCE(p.n, 0) - COALESCE(d.n, 0) AS diff
FROM (SELECT PLANT, COUNT(*) AS n FROM PROD_STAGING.SAP.BILLOFMATERIALS GROUP BY PLANT) p
FULL OUTER JOIN (SELECT PLANT, COUNT(*) AS n FROM DEV_RAW.SAP.BILLOFMATERIALS GROUP BY PLANT) d ON p.PLANT = d.PLANT
WHERE COALESCE(p.n, 0) <> COALESCE(d.n, 0)
ORDER BY ABS(diff) DESC;
